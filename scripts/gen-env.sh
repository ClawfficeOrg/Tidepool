#!/usr/bin/env bash
# Generate a .env for Tidepool from .env.example, with fresh secrets.
#
#   ./scripts/gen-env.sh [target]
#
# `target` defaults to `.env` in the repository root. The script refuses to
# overwrite an existing file: move or delete the old one first. It never prints
# a secret; the values exist only in the file it writes (mode 0600).
#
# What is generated:
#   JWT_SECRET                 64 random bytes, hex (128 chars)
#   TIDEPOOL_DB_PASSWORD       URL-safe random database password
#   TIDEPOOL_DB_ROOT_PASSWORD  URL-safe random root password
#   DATABASE_URL               rebuilt with the generated database password
#
# What is left for you, because it is deployment-specific:
#   TIDEPOOL_PUBLIC_ORIGIN     the hostname operators use
#   TIDEBOOT_*                 unattended first-run bootstrap, if you want it
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
example="$repo_root/.env.example"
target="${1:-$repo_root/.env}"

if [ ! -f "$example" ]; then
  echo "error: $example is missing; run this from a Tidepool checkout" >&2
  exit 1
fi

if [ -e "$target" ]; then
  echo "refusing to touch existing $target" >&2
  echo "move it aside first, for example: mv $target $target.$(date +%F-%H%M%S).bak" >&2
  exit 1
fi

# Random hex keeps every generated value URL-safe, so it can be dropped into
# DATABASE_URL without percent-encoding.
jwt_secret="$(openssl rand -hex 64)"
db_password="$(openssl rand -hex 24)"
db_root_password="$(openssl rand -hex 24)"

umask 077
# `set -o noclobber` closes the race between the check above and the write.
set -o noclobber
if ! {
  sed \
    -e "s|^JWT_SECRET=.*|JWT_SECRET=${jwt_secret}|" \
    -e "s|^DATABASE_URL=.*|DATABASE_URL=mysql://tidepool:${db_password}@localhost:3306/tidepool_dev|" \
    "$example"
  cat <<EOF

# ── Generated by scripts/gen-env.sh ──────────────────────────────────────────
# Read by docker-compose.yml for the stack's MySQL credentials.
TIDEPOOL_DB_PASSWORD=${db_password}
TIDEPOOL_DB_ROOT_PASSWORD=${db_root_password}
# Set this to the hostname operators use (also TIDEPOOL_PUBLIC_ORIGIN rules).
# TIDEPOOL_PUBLIC_ORIGIN=https://pool.example.com
EOF
} > "$target" 2>/dev/null; then
  echo "error: could not create $target (another process creating it?)" >&2
  exit 1
fi

chmod 600 "$target"

cat <<EOF
wrote $target (mode 600)

Generated: JWT_SECRET, TIDEPOOL_DB_PASSWORD, TIDEPOOL_DB_ROOT_PASSWORD.
Still edit before starting:
  1. TIDEPOOL_PUBLIC_ORIGIN — the address operators reach the pool on.
  2. TIDEBOOT_*             — only if you want the unattended first-run bootstrap.
Then: docker compose up -d
EOF
