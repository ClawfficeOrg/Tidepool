#!/usr/bin/env node
/**
 * Regenerate the pinned clawffice-design snapshot and the cell-sprite favicon
 * from a sibling checkout of `clawffice-design`.
 *
 * Usage:
 *   node src/lib/design/snapshot.mjs           # rewrite the snapshot
 *   node src/lib/design/snapshot.mjs --check   # fail when it would change
 *
 * The checkout is found at $CLAWFFICE_DESIGN_DIR, then `../clawffice-design`,
 * then `../../clawffice-design`, relative to this app.
 *
 * This is the only place the design system is read at build time: nothing is
 * fetched from a registry, and the committed snapshot keeps an offline clone
 * buildable. `design.drift.test.ts` compares the two when a checkout is present.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, '../../..');

const PALETTES = ['biolume', 'boiled', 'deep-tide', 'phosphor', 'sea-glass'];
const TOKEN_FILES = [
  'tokens/core.json',
  'tokens/apps/tidepool.json',
  'tokens/cells.json',
  ...PALETTES.map((name) => `tokens/palettes/${name}.json`),
];
const CELL_LEGEND = { '#': '#4A9FE0', o: '#F26B21', w: '#E9FBF6', k: '#06141B' };

/**
 * Find the design checkout.
 *
 * @returns {string | null} absolute path, or null when none is present
 */
export function locateDesignDir() {
  const candidates = [
    process.env.CLAWFFICE_DESIGN_DIR,
    join(appRoot, '..', 'clawffice-design'),
    join(appRoot, '..', '..', 'clawffice-design'),
  ].filter((candidate) => typeof candidate === 'string');
  for (const candidate of candidates) {
    if (existsSync(join(candidate, 'tokens', 'core.json'))) return resolve(candidate);
  }
  return null;
}

/**
 * Build the snapshot document for a design checkout.
 *
 * @param {string} designDir absolute path to `clawffice-design`
 * @returns {object} the snapshot document
 */
export function buildSnapshot(designDir) {
  const read = (relative) => JSON.parse(readFileSync(join(designDir, relative), 'utf8'));
  let commit = 'unknown';
  try {
    commit = execFileSync('git', ['-C', designDir, 'rev-parse', '--short=12', 'HEAD'], {
      encoding: 'utf8',
    }).trim();
  } catch {
    // A tarball checkout has no git metadata; the token files still match.
  }
  const palettes = {};
  for (const name of PALETTES) palettes[name] = read(`tokens/palettes/${name}.json`);
  return {
    $comment:
      'Pinned snapshot of clawffice-design tokens, generated by the tidepool-control-plane ' +
      'build from the sibling design checkout. Regenerate with `npm run design:snapshot`; ' +
      'src/lib/design/design.drift.test.ts fails when this drifts from the checkout.',
    source: { repo: 'clawffice-design', commit, files: TOKEN_FILES },
    core: read('tokens/core.json'),
    app: read('tokens/apps/tidepool.json'),
    palettes,
    cells: { pool: read('tokens/cells.json').sprites.pool },
  };
}

/**
 * Render the 12x12 "pool" cell sprite as a standalone SVG favicon.
 *
 * @param {string[][]} rows the sprite's rows, from `tokens/cells.json`
 * @returns {string} SVG markup
 */
export function renderCellSprite(rows) {
  const rects = [];
  rows.forEach((row, y) => {
    [...row].forEach((glyph, x) => {
      const fill = CELL_LEGEND[glyph];
      if (fill) rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`);
    });
  });
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" shape-rendering="crispEdges" ' +
    'role="img" aria-label="Tidepool cell sprite">\n  <rect width="12" height="12" fill="#06141B"/>\n  ' +
    rects.join('\n  ') +
    '\n</svg>\n'
  );
}

const check = process.argv.includes('--check');
const designDir = locateDesignDir();
if (!designDir) {
  console.error(
    'clawffice-design checkout not found. Set CLAWFFICE_DESIGN_DIR or clone it beside this app.',
  );
  process.exit(2);
}

/** Read the "pool" sprite rows out of a checkout. */
function readCellRows(dir) {
  const cells = JSON.parse(readFileSync(join(dir, 'tokens/cells.json'), 'utf8'));
  return cells.sprites.pool.rows;
}

const snapshot = `${JSON.stringify(buildSnapshot(designDir), null, 2)}\n`;
const cellSvg = renderCellSprite(readCellRows(designDir));

const targets = [
  [join(here, 'clawffice-design.snapshot.json'), snapshot],
  [join(appRoot, 'public/tidepool-cell.svg'), cellSvg],
];

let drifted = false;
for (const [path, next] of targets) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current === next) continue;
  drifted = true;
  if (check) {
    console.error(`drift: ${path} does not match ${designDir}`);
  } else {
    writeFileSync(path, next);
    console.log(`wrote ${path}`);
  }
}

if (check) {
  if (drifted) process.exit(1);
  console.log('design snapshot matches the checkout');
}
