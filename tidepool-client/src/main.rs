/// Items in the native tray context menu.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum MenuItem {
    OpenApp,
    OpenSettings,
    Quit,
}

impl MenuItem {
    fn label(&self) -> String {
        match self {
            Self::OpenApp => "Open App".to_string(),
            Self::OpenSettings => "Settings\u{2026}".to_string(),
            Self::Quit => "Quit".to_string(),
        }
    }
}

/// The ordered context-menu definition.
const MENU_ITEMS: [MenuItem; 3] = [MenuItem::OpenApp, MenuItem::OpenSettings, MenuItem::Quit];

/// Converts the menu items into `(item_id, label)` pairs for the native tray
/// menu. `item_id` is the index into [`MENU_ITEMS`], matching
/// [`resolve_menu_item`].
fn menu_entries() -> Vec<(u32, String)> {
    MENU_ITEMS
        .iter()
        .enumerate()
        .map(|(index, item)| (index as u32, item.label()))
        .collect()
}

/// Resolves a native menu item id back to its [`MenuItem`].
fn resolve_menu_item(native_id: u32) -> Option<MenuItem> {
    MENU_ITEMS.get(native_id as usize).copied()
}

/// Minimum gap between handled tray left-clicks.
///
/// Windows can deliver both `NIN_SELECT` and `WM_LBUTTONUP` for a single
/// click on the tray icon. The poll loop drains one event per 200ms tick, so
/// without coalescing the trailing event would arrive ~200ms later and
/// immediately toggle the popover back closed. Must exceed the poll interval.
const CLICK_COALESCE: Duration = Duration::from_millis(300);

/// The surfaces this build ships, chosen when the project was generated.
///
/// The tray template renders these values into the code, so the app never asks
/// at runtime what it is: a missing surface is a compile-time constant here and
/// the corresponding module is not even declared.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct AppShape {
    /// A native context menu on the tray icon.
    menu: bool,
    /// A popover window opened by a click on the icon.
    popup: bool,
    /// A main application window opened from "Open App".
    window: bool,
}

/// This project's shape: menu, popover and main window; nothing at launch.
const APP_SHAPE: AppShape = AppShape {
    menu: true,
    popup: true,
    window: true,
};

/// Whether a surface opens at launch.
///
/// False is the icon-only start: the process comes up with no window at all and
/// the menu's **Open App** item is what brings the main surface up.
const OPEN_ON_LAUNCH: bool = false;

/// What "Open App" (and open-on-launch) should show.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum MainSurface {
    /// The main application window.
    Window,
    /// The popover, for a project with no main window.
    Popover,
}

/// Resolves the main surface for a shape.
///
/// A window wins when the project has one; otherwise the popover is the main
/// surface. `None` means the project ships neither and only the menu is usable.
fn main_surface(shape: AppShape) -> Option<MainSurface> {
    if shape.window {
        Some(MainSurface::Window)
    } else if shape.popup {
        Some(MainSurface::Popover)
    } else {
        None
    }
}

/// What a left-click on the tray icon does.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ClickAction {
    /// Toggle the popover anchored to the icon.
    TogglePopover,
    /// The project has no popover, so a click does nothing.
    NoOp,
}

/// Resolves a left-click for a shape.
fn click_action(shape: AppShape) -> ClickAction {
    if shape.popup {
        ClickAction::TogglePopover
    } else {
        ClickAction::NoOp
    }
}

/// Opens the app's main surface: the main window when the project has one,
/// otherwise the popover.
///
/// This is what the "Open App" menu item (and, when configured, launch) calls,
/// so a project generated as menu+window opens its window while a menu+popup
/// project opens its popover — no per-project branching at the call sites.
fn open_main_surface(cx: &mut App, icon_rect: Option<tray_icon::IconAnchor>) {
    match main_surface(APP_SHAPE) {
        Some(MainSurface::Window) => {
            let display = icon_rect.and_then(|anchor| anchor.display_id(cx));
            main_window::open_main_window(cx, "Tidepool", "Tidepool", display);
            // A project with both surfaces opens the window as its main
            // surface; the popover stays reachable from a left-click on the
            // icon.
        }
        Some(MainSurface::Popover) => {
            toggle_popover_window(cx, "Tidepool", "Tidepool", icon_rect);
        }
        None => {}
    }
}

/// Manages the system tray / menubar icon: owns the `TrayIcon`, coalesces
/// duplicate left-clicks, and dispatches native context-menu selections.
struct TrayManager {
    tray: TrayIcon,
    last_left_click_at: Option<Instant>,
}

impl TrayManager {
    /// Creates a tray manager with the native context menu installed.
    fn new() -> Self {
        let mut tray = TrayIcon::new("Tidepool");
        #[cfg(any(target_os = "macos", target_os = "windows"))]
        if APP_SHAPE.menu {
            tray.set_menu(&menu_entries());
        }
        Self {
            tray,
            last_left_click_at: None,
        }
    }

    /// Returns whether a pending left-click occurred.
    fn poll_left_click(&self) -> bool {
        self.tray.poll_click()
    }

    /// Returns the next pending context-menu selection, if any.
    fn poll_menu_event(&self) -> Option<tray_icon::ContextMenuEvent> {
        self.tray.poll_context_menu()
    }

    /// Returns whether a second instance asked the first to surface its
    /// window (Windows-only).
    fn poll_show_request(&self) -> bool {
        self.tray.poll_show_request()
    }

    /// Where the tray icon is on screen, for anchoring windows.
    fn screen_rect(&self) -> Option<tray_icon::IconAnchor> {
        self.tray.anchor()
    }

    /// Handles a tray left-click by toggling the popover, anchored to the
    /// tray icon.
    ///
    /// Click events are coalesced within [`CLICK_COALESCE`]: a single physical
    /// click may surface as both `NIN_SELECT` and `WM_LBUTTONUP`, and the
    /// trailing event must not immediately toggle the popover back closed.
    ///
    /// With no popover surface this is a no-op: the menu (right-click) and the
    /// "Open App" item remain the way in.
    fn handle_left_click(&mut self, cx: &mut App) {
        if matches!(click_action(APP_SHAPE), ClickAction::NoOp) {
            // Menu is the only surface for this project: a left-click has
            // nothing to toggle, and the "Open App" item is the way in.
            let _ = cx;
            return;
        }
        let now = Instant::now();
        if self
            .last_left_click_at
            .is_some_and(|last| now.duration_since(last) < CLICK_COALESCE)
        {
            return;
        }
        self.last_left_click_at = Some(now);
        let rect = self.tray.anchor();
        toggle_popover_window(cx, "Tidepool", "Tidepool", rect);
    }

    /// Dispatches a context-menu selection by its item id.
    fn handle_menu_event(&mut self, item_id: u32, cx: &mut App) {
        let Some(item) = resolve_menu_item(item_id) else {
            return;
        };
        match item {
            MenuItem::OpenApp => {
                let rect = self.tray.anchor();
                open_main_surface(cx, rect);
            }
            MenuItem::OpenSettings => {
                let display = self.tray.anchor().and_then(|anchor| anchor.display_id(cx));
                settings_window::open_settings_window(cx, "Tidepool", display);
            }
            MenuItem::Quit => {
                let _ = std::fs::remove_file(lifecycle::default_lock_path().unwrap_or_default());
                cx.quit();
            }
        }
    }
}

impl gpui::Global for TrayManager {}

fn main() {
    gpui_kit::application()
        // A tray app must outlive its windows: the popover opens and closes as
        // the app runs, so the app must never auto-quit when the last window
        // closes. Quit is always explicit (tray menu / QuitAction).
        .with_quit_mode(gpui::QuitMode::Explicit)
        .run(|cx: &mut App| {
            gpui_kit::init(cx);

            // Scrollbar and toast settings come from the UI source's window
            // props, so this must run after `init` (which installs the theme)
            // and before any window opens.
            window_options::configure_theme(cx);

            // `init` installs the light theme; follow the system instead
            // until the user picks one in Settings.
            settings_window::apply_theme(settings_window::ThemeChoice::System, cx);

            // Enforce a single running instance via a lock file in the app
            // data directory. A second instance signals the first to surface
            // its window, then exits.
            let guard = match lifecycle::SingleInstanceGuard::acquire() {
                Ok(guard) => guard,
                Err(error) => {
                    #[cfg(target_os = "windows")]
                    {
                        if lifecycle::signal_existing_instance() {
                            eprintln!(
                                "Tidepool is already running — asked the existing instance to show its window."
                            );
                        } else {
                            eprintln!(
                                "Tidepool is already running — exiting ({error})."
                            );
                        }
                    }
                    #[cfg(not(target_os = "windows"))]
                    {
                        eprintln!("Tidepool is already running — exiting ({error}).");
                    }
                    cx.quit();
                    return;
                }
            };
            cx.set_global(guard);

            // Clean up the single-instance lock on SIGTERM/SIGINT so a
            // killed process doesn't leave a stale lock behind.
            {
                use signal_hook::low_level::register;
                // SAFETY: the closures only call `remove_file` and `exit`,
                // which are async-signal-safe in practice.
                let _ = unsafe {
                    register(signal_hook::consts::SIGTERM, || {
                        let _ = std::fs::remove_file(
                            lifecycle::default_lock_path().unwrap_or_default(),
                        );
                        std::process::exit(0);
                    })
                };
                let _ = unsafe {
                    register(signal_hook::consts::SIGINT, || {
                        let _ = std::fs::remove_file(
                            lifecycle::default_lock_path().unwrap_or_default(),
                        );
                        std::process::exit(0);
                    })
                };
            }

            cx.set_global(TrayManager::new());

            cx.on_action(|_: &QuitAction, cx: &mut App| {
                // Explicitly remove the lock file before quitting. GPUI
                // globals may not be dropped before process exit.
                let _ = std::fs::remove_file(
                    lifecycle::default_lock_path().unwrap_or_default(),
                );
                cx.quit();
            });

            // Poll the tray icon on each event-loop tick for left-clicks and
            // context-menu selections. The task is detached so it outlives
            // this closure; dropping the Task handle would cancel it.
            cx.spawn(|cx: &mut gpui::AsyncApp| {
                let cx = cx.clone();
                async move {
                    loop {
                        cx.background_executor()
                            .timer(Duration::from_millis(200))
                            .await;
                        cx.update(pump_tray);
                    }
                }
            })
            .detach();

            #[cfg(not(any(target_os = "macos", target_os = "windows")))]
            {
                // Linux: no tray support, so open the main surface immediately
                // and ignore the launch preference — with no icon to click,
                // starting hidden would leave the user no way back in.
                open_main_surface(cx, None);
            }

            // Open the configured launch surface, unless the project was
            // generated to start hidden with only its icon visible.
            #[cfg(any(target_os = "macos", target_os = "windows"))]
            if OPEN_ON_LAUNCH {
                let icon_rect = cx.try_global::<TrayManager>().and_then(|t| t.screen_rect());
                open_main_surface(cx, icon_rect);
            }
            // `OPEN_ON_LAUNCH = false`: start with only the icon visible. The
            // app is still fully usable — the tray menu's "Open App" item opens
            // the main surface (the window, for this project).
        });
}

/// Drain one poll cycle of the tray icon: a left-click toggles the popover,
/// a surface request from a second instance shows the popover, and a
/// context-menu selection dispatches the matching action.
fn pump_tray(cx: &mut App) {
    if !cx.has_global::<TrayManager>() {
        return;
    }
    let mut tray = cx.remove_global::<TrayManager>();
    let icon_rect = tray.screen_rect();
    if tray.poll_left_click() {
        tray.handle_left_click(cx);
    }
    if tray.poll_show_request() {
        if APP_SHAPE.popup {
            ensure_popover_window(cx, "Tidepool", "Tidepool", icon_rect);
        } else {
            open_main_surface(cx, icon_rect);
        }
    }
    if let Some(event) = tray.poll_menu_event() {
        tray.handle_menu_event(event.item_id, cx);
    }
    cx.set_global(tray);
}

/// Application quit action.
#[derive(Debug)]
struct QuitAction;

impl gpui::Action for QuitAction {
    fn boxed_clone(&self) -> Box<dyn gpui::Action> {
        Box::new(Self)
    }

    fn name(&self) -> &'static str {
        "quit"
    }

    fn name_for_type() -> &'static str
    where
        Self: Sized,
    {
        "quit"
    }

    fn partial_eq(&self, _other: &dyn gpui::Action) -> bool {
        true
    }

    fn build(_value: gpui::private::serde_json::Value) -> gpui::Result<Box<dyn gpui::Action>>
    where
        Self: Sized,
    {
        Ok(Box::new(Self))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn menu_entries_match_items() {
        let entries = menu_entries();
        assert_eq!(entries.len(), MENU_ITEMS.len());
        for (index, (id, label)) in entries.iter().enumerate() {
            assert_eq!(*id, index as u32);
            assert_eq!(label, &MENU_ITEMS[index].label());
        }
    }

    #[test]
    fn resolve_menu_item_round_trips() {
        for (index, item) in MENU_ITEMS.iter().enumerate() {
            assert_eq!(resolve_menu_item(index as u32), Some(*item));
        }
        assert_eq!(resolve_menu_item(MENU_ITEMS.len() as u32), None);
    }

    #[test]
    fn open_app_is_the_first_menu_item() {
        // The whole point of a taskbar app is that the main surface is
        // reachable from the menu, so pin its position rather than trusting
        // the array literal to stay put.
        assert_eq!(MENU_ITEMS[0], MenuItem::OpenApp);
        assert_eq!(MENU_ITEMS[0].label(), "Open App");
    }

    #[test]
    #[allow(clippy::assertions_on_constants)] // the generated shape is a constant on purpose
    fn starts_icon_only() {
        // Generated with `open_on_launch = false`: the process must come up
        // with only its tray icon. A regression here is a Dock entry and a
        // window appearing at login.
        assert!(!OPEN_ON_LAUNCH);
    }

    #[test]
    #[allow(clippy::assertions_on_constants)] // the generated shape is a constant on purpose
    fn ships_menu_popover_and_window() {
        assert!(APP_SHAPE.menu, "the menu is the always-available way in");
        assert!(APP_SHAPE.popup, "a click on the icon must open the popover");
        assert!(APP_SHAPE.window, "the main window is opened on demand");
    }

    #[test]
    fn a_click_on_the_icon_opens_the_popover() {
        assert_eq!(click_action(APP_SHAPE), ClickAction::TogglePopover);
    }

    #[test]
    fn open_app_opens_the_main_window() {
        assert_eq!(main_surface(APP_SHAPE), Some(MainSurface::Window));
    }

    #[test]
    fn a_project_without_a_window_falls_back_to_the_popover() {
        let shape = AppShape {
            menu: true,
            popup: true,
            window: false,
        };
        assert_eq!(main_surface(shape), Some(MainSurface::Popover));
        assert_eq!(click_action(shape), ClickAction::TogglePopover);
    }

    #[test]
    fn a_menu_only_project_has_no_click_target() {
        let shape = AppShape {
            menu: true,
            popup: false,
            window: false,
        };
        assert_eq!(main_surface(shape), None);
        assert_eq!(click_action(shape), ClickAction::NoOp);
    }
}
