//! The client's own settings store.
//!
//! One JSON file per user, outside any repository:
//! `$TIDEPOOL_CLIENT_HOME/settings.json` when that variable is set, otherwise
//! the platform's per-user configuration directory under
//! `com.clawffice.Tidepool`. The store holds the pool URL, the operator's JWT
//! and this machine's host relationship credential — the last is the secret the
//! pool stores only as a hash, so it is never written anywhere else, never
//! logged and never placed in a layout file.
//!
//! Two rules keep that promise mechanical:
//!
//! - [`SettingsStore::save`] refuses a path inside a git working tree, so the
//!   file cannot be committed by accident, and writes atomically with `0600`
//!   permissions where the platform has them.
//! - [`ClientSettings`]'s `Debug` redacts every secret, so a panic, a log line
//!   or a `dbg!` cannot leak one. [`redact`] is the only way a secret is
//!   rendered, and it keeps at most four leading characters.
//!
//! A file that exists but does not parse is reported as
//! [`SettingsError::Corrupt`] and left in place: the client never silently
//! replaces settings it could not read. The rest of the app keeps working with
//! an empty store, which is what makes an unreachable pool harmless.

use std::collections::BTreeMap;
use std::fs;
use std::io::{self, Write as _};
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use thiserror::Error;

/// Environment variable that relocates the store to a directory.
///
/// Mirrors the CLI's `TIDEPOOL_HOME`, but is deliberately a different variable:
/// the client's host credential is its own, and pointing both skins at one file
/// would mix a host secret with an operator store.
pub const HOME_ENV: &str = "TIDEPOOL_CLIENT_HOME";
/// Name of the store file inside its directory.
pub const STORE_FILE: &str = "settings.json";

/// What could not be done with the settings store.
///
/// No variant carries a secret: paths and error kinds only.
#[derive(Debug, Error)]
pub enum SettingsError {
    /// No per-user configuration directory could be found.
    #[error("no per-user configuration directory for {0}")]
    NoConfigDir(&'static str),
    /// A store file exists but is not valid settings.
    ///
    /// The file is left untouched; the caller decides whether to report it.
    #[error("settings at {path} are not valid JSON or do not match the schema")]
    Corrupt {
        /// The file that could not be parsed.
        path: PathBuf,
    },
    /// The store could not be read.
    #[error("could not read settings at {path}: {source}")]
    Read {
        /// The file that could not be read.
        path: PathBuf,
        /// The underlying I/O error.
        source: io::Error,
    },
    /// The store could not be written.
    #[error("could not write settings at {path}: {source}")]
    Write {
        /// The file that could not be written.
        path: PathBuf,
        /// The underlying I/O error.
        source: io::Error,
    },
    /// The settings could not be encoded as JSON.
    #[error("could not encode settings: {0}")]
    Encode(serde_json::Error),
    /// The store path sits inside a git working tree.
    #[error("refusing to write settings inside a git working tree: {path}")]
    InsideRepository {
        /// The refused path.
        path: PathBuf,
    },
}

/// One enrolled machine, as the client remembers it.
///
/// `credential` is the long-lived host relationship secret. It is generated on
/// this machine, stored here and nowhere else, and the pool holds only its
/// Argon2id hash.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct StoredHost {
    /// The host relationship credential generated by this machine.
    pub credential: String,
    /// The pool's mutable slug for the host.
    #[serde(default)]
    pub slug: String,
    /// The hostname reported at enrollment.
    #[serde(default)]
    pub hostname: String,
    /// The display name shown in the pool.
    #[serde(default)]
    pub display_name: String,
}

impl std::fmt::Debug for StoredHost {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("StoredHost")
            .field("credential", &redact(&self.credential))
            .field("slug", &self.slug)
            .field("hostname", &self.hostname)
            .field("display_name", &self.display_name)
            .finish()
    }
}

/// Everything the client keeps between launches.
///
/// `Debug` prints the shape and redacted secrets, never a full credential or
/// token.
#[derive(Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ClientSettings {
    /// The pool this client was last signed in to.
    #[serde(default)]
    pub pool_url: Option<String>,
    /// The operator JWT for that pool.
    #[serde(default)]
    pub member_token: Option<String>,
    /// The signed-in operator's email, for display.
    #[serde(default)]
    pub member_email: Option<String>,
    /// Host relationship credentials, keyed by host id.
    #[serde(default)]
    pub hosts: BTreeMap<String, StoredHost>,
    /// The host this machine enrolled most recently.
    #[serde(default)]
    pub active_host: Option<String>,
}

impl std::fmt::Debug for ClientSettings {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("ClientSettings")
            .field("pool_url", &self.pool_url)
            .field("member_email", &self.member_email)
            .field("member_token", &self.member_token.as_deref().map(redact))
            .field("hosts", &self.hosts)
            .field("active_host", &self.active_host)
            .finish()
    }
}

impl ClientSettings {
    /// Record a successful sign-in.
    pub fn remember_sign_in(&mut self, pool_url: String, email: String, token: String) {
        self.pool_url = Some(pool_url);
        self.member_email = Some(email);
        self.member_token = Some(token);
    }

    /// Forget the pool session, keeping enrolled-host credentials.
    ///
    /// A host credential is independent of the operator's JWT: signing out must
    /// not strand a machine that is still a member of the pool.
    pub fn forget_sign_in(&mut self) {
        self.member_token = None;
        self.member_email = None;
    }

    /// Remember a host this machine enrolled and make it the active one.
    pub fn record_host(&mut self, id: String, host: StoredHost) {
        self.active_host = Some(id.clone());
        self.hosts.insert(id, host);
    }

    /// The active host's id and its stored record, when this machine has one.
    pub fn active_host(&self) -> Option<(&str, &StoredHost)> {
        let id = self.active_host.as_deref()?;
        self.hosts.get(id).map(|host| (id, host))
    }

    /// Forget one host; the active host is cleared when it was the one removed.
    pub fn forget_host(&mut self, id: &str) {
        self.hosts.remove(id);
        if self.active_host.as_deref() == Some(id) {
            self.active_host = None;
        }
    }
}

/// Render a secret so a person can tell which one it is without receiving it.
///
/// A short secret is not shown at all; a long one keeps four leading characters
/// so a store and a pool can be compared, never the whole value.
pub fn redact(secret: &str) -> String {
    let count = secret.chars().count();
    if count <= 8 {
        return format!("<redacted; {count} chars>");
    }
    let prefix: String = secret.chars().take(4).collect();
    format!("{prefix}…<redacted; {count} chars>")
}

/// The settings file and where it came from.
pub struct SettingsStore {
    path: PathBuf,
    settings: ClientSettings,
    present: bool,
}

impl std::fmt::Debug for SettingsStore {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("SettingsStore")
            .field("path", &self.path)
            .field("present", &self.present)
            .field("settings", &self.settings)
            .finish()
    }
}

impl SettingsStore {
    /// The default store path for this user.
    pub fn default_path() -> Result<PathBuf, SettingsError> {
        if let Some(home) = std::env::var_os(HOME_ENV) {
            return Ok(PathBuf::from(home).join(STORE_FILE));
        }
        directories::ProjectDirs::from("com", "clawffice", "Tidepool")
            .map(|dirs| dirs.config_dir().join(STORE_FILE))
            .ok_or(SettingsError::NoConfigDir("Tidepool"))
    }

    /// Open the default store.
    pub fn open() -> Result<Self, SettingsError> {
        Self::open_at(Self::default_path()?)
    }

    /// Open the store at `path`, treating a missing file as empty settings.
    pub fn open_at(path: PathBuf) -> Result<Self, SettingsError> {
        match fs::read(&path) {
            Ok(bytes) => match serde_json::from_slice(&bytes) {
                Ok(settings) => Ok(Self {
                    path,
                    settings,
                    present: true,
                }),
                Err(_) => Err(SettingsError::Corrupt { path }),
            },
            Err(source) if source.kind() == io::ErrorKind::NotFound => Ok(Self {
                path,
                settings: ClientSettings::default(),
                present: false,
            }),
            Err(source) => Err(SettingsError::Read { path, source }),
        }
    }

    /// An empty store at `path` that has not read the file.
    ///
    /// Used when the file could not be read (or there is no configuration
    /// directory): the app keeps its local surfaces and reports the problem,
    /// rather than failing to start because a pool setting is broken.
    pub fn empty_at(path: PathBuf) -> Self {
        Self {
            path,
            settings: ClientSettings::default(),
            present: false,
        }
    }

    /// The settings as loaded.
    pub fn settings(&self) -> &ClientSettings {
        &self.settings
    }

    /// The settings, mutable. Call [`SettingsStore::save`] to persist a change.
    pub fn settings_mut(&mut self) -> &mut ClientSettings {
        &mut self.settings
    }

    /// The file this store reads and writes.
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Whether the file existed when the store was opened.
    pub fn present(&self) -> bool {
        self.present
    }

    /// Write the settings atomically, with `0600` permissions on Unix.
    ///
    /// The temporary file is created next to the destination, so a crash leaves
    /// either the old file or the new one, never a half-written secret. A path
    /// inside a git working tree is refused before anything is created.
    pub fn save(&self) -> Result<(), SettingsError> {
        if inside_repository(&self.path) {
            return Err(SettingsError::InsideRepository {
                path: self.path.clone(),
            });
        }
        if let Some(parent) = self.path.parent() {
            fs::create_dir_all(parent).map_err(|source| SettingsError::Write {
                path: self.path.clone(),
                source,
            })?;
        }
        let bytes = serde_json::to_vec_pretty(&self.settings).map_err(SettingsError::Encode)?;
        let temporary = temporary_path(&self.path);
        let result =
            write_private(&temporary, &bytes).and_then(|()| replace_file(&temporary, &self.path));
        if let Err(source) = result {
            let _ = fs::remove_file(&temporary);
            return Err(SettingsError::Write {
                path: self.path.clone(),
                source,
            });
        }
        Ok(())
    }
}

/// Replace `destination` with `temporary`.
///
/// On Unix `rename` replaces atomically. The Windows standard library has no
/// atomic replace, so the destination is removed first; the temporary file is
/// already complete by then, so a crash cannot leave a half-written secret.
fn replace_file(temporary: &Path, destination: &Path) -> io::Result<()> {
    #[cfg(windows)]
    {
        if destination.exists() {
            fs::remove_file(destination)?;
        }
    }
    fs::rename(temporary, destination)
}

/// Create `path` with `0600` on Unix and write `bytes`, syncing before return.
fn write_private(path: &Path, bytes: &[u8]) -> io::Result<()> {
    let mut options = fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt as _;
        options.mode(0o600);
    }
    let mut file = options.open(path)?;
    file.write_all(bytes)?;
    file.sync_all()
}

/// The sibling temporary path used for the atomic replace.
fn temporary_path(destination: &Path) -> PathBuf {
    let name = destination
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_else(|| STORE_FILE.to_owned());
    destination.with_file_name(format!(".{name}.{}.tmp", std::process::id()))
}

/// Whether `path` is inside a git working tree.
///
/// The walk is lexical on the path the caller supplied; the default store path
/// is absolute, and a caller that passes a relative path gets the same answer
/// the operating system would resolve.
fn inside_repository(path: &Path) -> bool {
    path.ancestors()
        .any(|ancestor| ancestor.join(".git").exists())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn scratch(label: &str) -> PathBuf {
        let unique = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|elapsed| elapsed.as_nanos())
            .unwrap_or_default();
        let dir = std::env::temp_dir().join(format!(
            "tidepool-client-settings-{label}-{}-{unique}",
            std::process::id()
        ));
        fs::create_dir_all(&dir).expect("scratch directory");
        dir
    }

    fn sample() -> ClientSettings {
        let mut settings = ClientSettings::default();
        settings.remember_sign_in(
            "http://127.0.0.1:8080".to_owned(),
            "operator@example.test".to_owned(),
            "jwt-token-that-must-not-be-printed".to_owned(),
        );
        settings.record_host(
            "host-public-id".to_owned(),
            StoredHost {
                credential: "0123456789abcdef0123456789abcdef".to_owned(),
                slug: "build-box".to_owned(),
                hostname: "build-box.local".to_owned(),
                display_name: "Build box".to_owned(),
            },
        );
        settings
    }

    #[test]
    fn round_trips_through_the_store() {
        let dir = scratch("round-trip");
        let path = dir.join(STORE_FILE);
        let mut store = SettingsStore::open_at(path.clone()).expect("open missing");
        assert!(!store.present());
        *store.settings_mut() = sample();
        store.save().expect("save");

        let reloaded = SettingsStore::open_at(path).expect("reload");
        assert_eq!(reloaded.settings(), &sample());
        assert!(reloaded.present());
    }

    #[test]
    fn saving_twice_replaces_the_previous_file() {
        let dir = scratch("replace");
        let path = dir.join(STORE_FILE);
        let mut store = SettingsStore::open_at(path.clone()).expect("open");
        *store.settings_mut() = sample();
        store.save().expect("first save");
        store.settings_mut().forget_sign_in();
        store.save().expect("replace");
        let reloaded = SettingsStore::open_at(path).expect("reload");
        assert!(reloaded.settings().member_token.is_none());
        assert!(reloaded.settings().active_host().is_some());
    }

    #[test]
    fn missing_file_is_empty_settings_not_an_error() {
        let dir = scratch("missing");
        let store = SettingsStore::open_at(dir.join("absent.json")).expect("open");
        assert_eq!(store.settings(), &ClientSettings::default());
        assert!(!store.present());
    }

    #[test]
    fn corrupt_file_is_reported_and_left_in_place() {
        let dir = scratch("corrupt");
        let path = dir.join(STORE_FILE);
        fs::write(&path, b"{ this is not json").expect("seed");
        let error = SettingsStore::open_at(path.clone()).expect_err("corrupt");
        assert!(matches!(error, SettingsError::Corrupt { .. }));
        assert_eq!(fs::read(&path).expect("still there"), b"{ this is not json");
    }

    #[test]
    fn refuses_to_write_inside_a_git_working_tree() {
        let dir = scratch("repo");
        fs::create_dir_all(dir.join(".git")).expect("fake git dir");
        let path = dir.join("nested").join(STORE_FILE);
        let mut store = SettingsStore::open_at(path.clone()).expect("open");
        *store.settings_mut() = sample();
        let error = store.save().expect_err("refused");
        assert!(matches!(error, SettingsError::InsideRepository { .. }));
        assert!(!path.exists(), "nothing may be created for a refused path");
    }

    #[cfg(unix)]
    #[test]
    fn store_file_is_owner_only() {
        use std::os::unix::fs::PermissionsExt as _;
        let dir = scratch("mode");
        let path = dir.join(STORE_FILE);
        let mut store = SettingsStore::open_at(path.clone()).expect("open");
        *store.settings_mut() = sample();
        store.save().expect("save");
        let mode = fs::metadata(&path).expect("metadata").permissions().mode();
        assert_eq!(mode & 0o777, 0o600);
    }

    #[test]
    fn save_leaves_no_temporary_file_behind() {
        let dir = scratch("atomic");
        let path = dir.join(STORE_FILE);
        let mut store = SettingsStore::open_at(path.clone()).expect("open");
        *store.settings_mut() = sample();
        store.save().expect("save");
        let entries: Vec<_> = fs::read_dir(&dir)
            .expect("read dir")
            .map(|entry| entry.expect("entry").file_name())
            .collect();
        assert_eq!(
            entries,
            vec![std::ffi::OsString::from(STORE_FILE)],
            "the store is the only file written"
        );
    }

    #[test]
    fn debug_never_shows_a_secret() {
        let settings = sample();
        let rendered = format!("{settings:?}");
        assert!(!rendered.contains("jwt-token-that-must-not-be-printed"));
        assert!(!rendered.contains("0123456789abcdef0123456789abcdef"));
        assert!(rendered.contains("operator@example.test"));
        assert!(rendered.contains("build-box"));
    }

    #[test]
    fn redact_keeps_only_a_prefix() {
        assert_eq!(redact("short"), "<redacted; 5 chars>");
        let long = redact("abcdefghijklmnop");
        assert!(long.starts_with("abcd"));
        assert!(!long.contains("efgh"));
        assert!(long.contains("16 chars"));
    }

    #[test]
    fn forgetting_a_host_clears_the_active_pointer() {
        let mut settings = sample();
        settings.forget_host("host-public-id");
        assert!(settings.active_host().is_none());
        assert!(settings.hosts.is_empty());
    }

    #[test]
    fn signing_out_keeps_host_credentials() {
        let mut settings = sample();
        settings.forget_sign_in();
        assert!(settings.member_token.is_none());
        assert!(settings.active_host().is_some());
    }

    #[test]
    fn default_path_ends_with_the_store_file() {
        let path = SettingsStore::default_path().expect("a per-user directory");
        assert!(path.ends_with(STORE_FILE));
        assert!(!inside_repository(
            &Path::new("/tmp").join("tidepool-settings.json")
        ));
    }
}
