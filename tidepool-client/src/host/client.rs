//! The pool, as this machine talks to it.
//!
//! [`PoolApi`] is the whole network surface this feature needs: the operator
//! sign-in, the two-step host enrollment the CLI performs, the host's status
//! and the execution grant. [`HttpPool`] is the implementation over the pool's
//! documented HTTP API; the tests script the trait instead and one test drives
//! the real HTTP implementation against a local pool that speaks the same
//! routes.
//!
//! # Credentials
//!
//! Two secrets cross this module. The operator JWT is carried in
//! [`Session`] and the host relationship credential is generated by the caller
//! of [`PoolApi::enroll`]. Both have hand-written `Debug` implementations that
//! redact them, no error variant carries either, and nothing here logs a
//! request body. A host id taken from the pool is validated before it is put
//! into a path, so a malformed id cannot address another route.

use std::time::Duration;

use serde::de::DeserializeOwned;
use serde::{Deserialize, Serialize};
use thiserror::Error;

/// How long a connect may take before the pool is called unreachable.
const CONNECT_TIMEOUT: Duration = Duration::from_secs(3);
/// How long a read may take before the pool is called unreachable.
const READ_TIMEOUT: Duration = Duration::from_secs(10);

/// What could not be done with the pool.
///
/// No variant carries a credential or a request body.
#[derive(Debug, Error)]
pub enum PoolError {
    /// The pool URL is not an `http`/`https` URL with a host.
    #[error("`{url}` is not a usable pool URL (expected http:// or https:// and a host)")]
    InvalidPoolUrl {
        /// The rejected input.
        url: String,
    },
    /// The pool could not be reached, or the connection failed.
    ///
    /// This is the only error an unreachable pool produces, and it is never
    /// fatal to the local app.
    #[error("the pool could not be reached: {detail}")]
    Unreachable {
        /// The transport's description.
        detail: String,
    },
    /// The pool answered `401`: the session has ended or the credentials are wrong.
    #[error("the pool did not accept these credentials")]
    Unauthorized,
    /// The pool answered `403`: the operator's role may not do this.
    #[error("the pool refused this action: {detail}")]
    Forbidden {
        /// The problem detail, when the pool sent one.
        detail: String,
    },
    /// The pool answered with an error problem document.
    #[error("the pool answered {status} ({code}){detail}")]
    Problem {
        /// HTTP status.
        status: u16,
        /// The pool's problem code, or the status reason when absent.
        code: String,
        /// The problem detail, empty when absent.
        detail: String,
    },
    /// A response was not the documented JSON shape.
    #[error("the pool's answer was not understood: {detail}")]
    Protocol {
        /// What was wrong.
        detail: String,
    },
}

/// One operator, as `POST /v1/pool/login` reports them.
#[derive(Debug, Clone, Default, PartialEq, Eq, Deserialize)]
pub struct PoolUser {
    /// Public operator id.
    #[serde(default)]
    pub id: String,
    /// Login email.
    #[serde(default)]
    pub email: String,
    /// Display name.
    #[serde(default)]
    pub display_name: String,
    /// Role inside the organization (`owner`, `admin`, `member`, `viewer`).
    #[serde(default)]
    pub role: String,
}

/// A signed-in operator session.
///
/// `Debug` redacts the token.
#[derive(Clone)]
pub struct Session {
    pool_url: String,
    token: String,
    email: String,
    role: String,
    must_change_password: bool,
}

impl std::fmt::Debug for Session {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("Session")
            .field("pool_url", &self.pool_url)
            .field("token", &crate::settings::redact(&self.token))
            .field("email", &self.email)
            .field("role", &self.role)
            .field("must_change_password", &self.must_change_password)
            .finish()
    }
}

impl Session {
    fn new(pool_url: String, token: String, user: PoolUser, must_change_password: bool) -> Self {
        Self {
            pool_url,
            token,
            email: user.email,
            role: user.role,
            must_change_password,
        }
    }

    /// Rebuild the session a previous launch saved in the settings store.
    ///
    /// The role and the password-change flag are not persisted, so they are
    /// left empty here; [`PoolApi::sign_in`] fills them on the next sign-in.
    pub(crate) fn from_stored(pool_url: &str, email: &str, token: &str) -> Self {
        Self {
            pool_url: pool_url.to_owned(),
            token: token.to_owned(),
            email: email.to_owned(),
            role: String::new(),
            must_change_password: false,
        }
    }

    /// A session for a scripted pool in tests.
    #[cfg(test)]
    pub(crate) fn for_test(pool_url: &str, email: &str, token: &str) -> Self {
        Self {
            pool_url: pool_url.to_owned(),
            token: token.to_owned(),
            email: email.to_owned(),
            role: "owner".to_owned(),
            must_change_password: false,
        }
    }

    /// The pool this session belongs to.
    pub fn pool_url(&self) -> &str {
        &self.pool_url
    }

    /// The signed-in operator's email.
    pub fn email(&self) -> &str {
        &self.email
    }

    /// The operator's role.
    pub fn role(&self) -> &str {
        &self.role
    }

    /// Whether the pool requires a password change before normal use.
    pub fn must_change_password(&self) -> bool {
        self.must_change_password
    }

    /// The bearer token. Crate-private so a UI cannot print it by accident.
    pub(crate) fn token(&self) -> &str {
        &self.token
    }
}

/// A host's presence, as the pool reports it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HostStatus {
    /// Enrolled and waiting for an operator's approval.
    PendingApproval,
    /// Holding a live presence connection.
    Connected,
    /// Enrolled but with no live connection.
    Offline,
    /// Revoked by an operator.
    Revoked,
    /// A status this build does not know; never read as connected.
    Unknown(String),
}

impl HostStatus {
    /// Parse the pool's wire value.
    pub fn parse(value: &str) -> Self {
        match value {
            "pending_approval" => Self::PendingApproval,
            "connected" => Self::Connected,
            "offline" => Self::Offline,
            "revoked" => Self::Revoked,
            other => Self::Unknown(other.to_owned()),
        }
    }

    /// The words this status is shown with.
    pub fn label(&self) -> &str {
        match self {
            Self::PendingApproval => "waiting for approval",
            Self::Connected => "connected",
            Self::Offline => "offline",
            Self::Revoked => "revoked",
            Self::Unknown(value) => value,
        }
    }

    /// The pool's wire value.
    pub fn as_str(&self) -> &str {
        match self {
            Self::PendingApproval => "pending_approval",
            Self::Connected => "connected",
            Self::Offline => "offline",
            Self::Revoked => "revoked",
            Self::Unknown(value) => value,
        }
    }
}

/// One enrolled machine, as the pool reports it.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct HostView {
    /// Public host id.
    pub id: String,
    /// Mutable slug.
    #[serde(default)]
    pub slug: String,
    /// Display name.
    #[serde(default)]
    pub display_name: String,
    /// Hostname reported at enrollment.
    #[serde(default)]
    pub hostname: String,
    /// Presence, as a wire value.
    #[serde(default)]
    pub status: String,
    /// Whether `host.execute` is granted.
    #[serde(default)]
    pub execution_enabled: bool,
}

impl HostView {
    /// The parsed presence.
    pub fn host_status(&self) -> HostStatus {
        HostStatus::parse(&self.status)
    }
}

/// What this feature needs from a pool.
///
/// One method per request, so a scripted implementation in the tests has the
/// same shape as [`HttpPool`] and cannot accidentally share logic with it.
pub trait PoolApi {
    /// Verify an operator's credentials and keep the session.
    fn sign_in(
        &mut self,
        pool_url: &str,
        email: &str,
        password: &str,
    ) -> Result<Session, PoolError>;

    /// Read every live host.
    fn list_hosts(&mut self, session: &Session) -> Result<Vec<HostView>, PoolError>;

    /// Register a host under `hostname`.
    fn create_host(
        &mut self,
        session: &Session,
        hostname: &str,
        display_name: Option<&str>,
    ) -> Result<HostView, PoolError>;

    /// Mint the ten-minute single-use enrollment token for `host_id`.
    fn mint_enrollment_token(
        &mut self,
        session: &Session,
        host_id: &str,
    ) -> Result<String, PoolError>;

    /// Exchange the token for the machine-generated credential.
    fn enroll(
        &mut self,
        pool_url: &str,
        token: &str,
        credential: &str,
    ) -> Result<HostView, PoolError>;

    /// Grant `host.execute` so the machine may run agents.
    fn grant_execution(&mut self, session: &Session, host_id: &str) -> Result<HostView, PoolError>;

    /// Revoke `host.execute`; the machine stays connected but runs nothing.
    fn revoke_execution(&mut self, session: &Session, host_id: &str)
    -> Result<HostView, PoolError>;
}

/// The pool's HTTP API, over `ureq`.
///
/// The agent has short connect and read timeouts on purpose: a pool that is
/// away must cost the local app a moment, never a hang.
pub struct HttpPool {
    agent: ureq::Agent,
}

impl std::fmt::Debug for HttpPool {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.debug_struct("HttpPool").finish_non_exhaustive()
    }
}

impl Default for HttpPool {
    fn default() -> Self {
        Self::new()
    }
}

impl HttpPool {
    /// Build the HTTP pool client.
    pub fn new() -> Self {
        let agent = ureq::AgentBuilder::new()
            .timeout_connect(CONNECT_TIMEOUT)
            .timeout_read(READ_TIMEOUT)
            .timeout_write(READ_TIMEOUT)
            .build();
        Self { agent }
    }

    fn authorized(&self, session: &Session, method: &str, path: &str) -> ureq::Request {
        self.agent
            .request(method, &format!("{}{path}", session.pool_url))
            .set("Authorization", &format!("Bearer {}", session.token()))
            .set("Accept", "application/json")
    }
}

impl PoolApi for HttpPool {
    fn sign_in(
        &mut self,
        pool_url: &str,
        email: &str,
        password: &str,
    ) -> Result<Session, PoolError> {
        let base = normalize_pool_url(pool_url)?;
        let response = self
            .agent
            .post(&format!("{base}/v1/pool/login"))
            .set("Accept", "application/json")
            .send_json(serde_json::json!({ "email": email, "password": password }));
        let body: LoginResponse = decode(response)?;
        Ok(Session::new(
            base,
            body.token,
            body.user,
            body.must_change_password,
        ))
    }

    fn list_hosts(&mut self, session: &Session) -> Result<Vec<HostView>, PoolError> {
        let response = self.authorized(session, "GET", "/v1/hosts").call();
        let body: HostsResponse = decode(response)?;
        Ok(body.hosts)
    }

    fn create_host(
        &mut self,
        session: &Session,
        hostname: &str,
        display_name: Option<&str>,
    ) -> Result<HostView, PoolError> {
        let response = self
            .authorized(session, "POST", "/v1/hosts")
            .send_json(serde_json::json!({ "hostname": hostname, "display_name": display_name }));
        decode(response)
    }

    fn mint_enrollment_token(
        &mut self,
        session: &Session,
        host_id: &str,
    ) -> Result<String, PoolError> {
        let host_id = safe_id(host_id)?;
        let response = self
            .authorized(
                session,
                "POST",
                &format!("/v1/hosts/{host_id}/enrollment-tokens"),
            )
            .send_json(serde_json::json!({ "host_id": host_id }));
        let body: MintedToken = decode(response)?;
        Ok(body.token)
    }

    fn enroll(
        &mut self,
        pool_url: &str,
        token: &str,
        credential: &str,
    ) -> Result<HostView, PoolError> {
        let base = normalize_pool_url(pool_url)?;
        let response = self
            .agent
            .post(&format!("{base}/v1/hosts/enroll"))
            .set("Accept", "application/json")
            .send_json(serde_json::json!({ "token": token, "credential": credential }));
        decode(response)
    }

    fn grant_execution(&mut self, session: &Session, host_id: &str) -> Result<HostView, PoolError> {
        let host_id = safe_id(host_id)?;
        let response = self
            .authorized(session, "POST", &format!("/v1/hosts/{host_id}/execution"))
            .call();
        decode(response)
    }

    fn revoke_execution(
        &mut self,
        session: &Session,
        host_id: &str,
    ) -> Result<HostView, PoolError> {
        let host_id = safe_id(host_id)?;
        let response = self
            .authorized(session, "DELETE", &format!("/v1/hosts/{host_id}/execution"))
            .call();
        decode(response)
    }
}

#[derive(Debug, Deserialize)]
struct LoginResponse {
    token: String,
    #[serde(default)]
    user: PoolUser,
    #[serde(default)]
    must_change_password: bool,
}

#[derive(Debug, Deserialize)]
struct HostsResponse {
    #[serde(default)]
    hosts: Vec<HostView>,
}

#[derive(Debug, Deserialize)]
struct MintedToken {
    token: String,
}

#[derive(Debug, Deserialize)]
struct ProblemBody {
    #[serde(default)]
    code: Option<String>,
    #[serde(default)]
    detail: Option<String>,
    #[serde(default)]
    title: Option<String>,
}

/// Normalise and validate a pool URL.
///
/// The base may include a path (a pool behind a reverse proxy), but not a
/// query, a fragment or embedded credentials, and it must name a host with an
/// `http`/`https` scheme. The returned value has no trailing slash, so request
/// paths are appended with one `/`.
pub fn normalize_pool_url(input: &str) -> Result<String, PoolError> {
    let trimmed = input.trim();
    let invalid = || PoolError::InvalidPoolUrl {
        url: trimmed.to_owned(),
    };
    if trimmed.is_empty() || !trimmed.is_ascii() {
        return Err(invalid());
    }
    if trimmed.contains('?') || trimmed.contains('#') || trimmed.chars().any(char::is_whitespace) {
        return Err(invalid());
    }
    let lower = trimmed.to_ascii_lowercase();
    let rest = if lower.starts_with("http://") {
        &trimmed["http://".len()..]
    } else if lower.starts_with("https://") {
        &trimmed["https://".len()..]
    } else {
        return Err(invalid());
    };
    let authority_end = rest.find('/').unwrap_or(rest.len());
    let authority = &rest[..authority_end];
    if authority.is_empty() || authority.starts_with('@') || authority.contains('@') {
        return Err(invalid());
    }
    let base = trimmed.trim_end_matches('/');
    if base.is_empty() {
        return Err(invalid());
    }
    Ok(base.to_owned())
}

/// Validate a host id before it is put into a path.
fn safe_id(id: &str) -> Result<&str, PoolError> {
    let valid = !id.is_empty()
        && id
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || matches!(character, '-' | '_'));
    if valid {
        Ok(id)
    } else {
        Err(PoolError::Protocol {
            detail: "the pool returned a host id that is not path-safe".to_owned(),
        })
    }
}

/// Turn one HTTP result into a typed body, mapping the pool's errors.
fn decode<T: DeserializeOwned>(
    result: Result<ureq::Response, ureq::Error>,
) -> Result<T, PoolError> {
    let response = match result {
        Ok(response) => response,
        Err(ureq::Error::Transport(transport)) => {
            return Err(PoolError::Unreachable {
                detail: transport.to_string(),
            });
        }
        Err(ureq::Error::Status(status, response)) => {
            return Err(status_error(status, response));
        }
    };
    let body = response
        .into_string()
        .map_err(|source| PoolError::Protocol {
            detail: source.to_string(),
        })?;
    serde_json::from_str(&body).map_err(|source| PoolError::Protocol {
        detail: source.to_string(),
    })
}

/// Map a non-2xx answer to a [`PoolError`].
fn status_error(status: u16, response: ureq::Response) -> PoolError {
    let body = response.into_string().unwrap_or_default();
    let problem: Option<ProblemBody> = serde_json::from_str(&body).ok();
    let detail = problem
        .as_ref()
        .and_then(|problem| problem.detail.clone().or_else(|| problem.title.clone()))
        .unwrap_or_default();
    match status {
        401 => PoolError::Unauthorized,
        403 => PoolError::Forbidden { detail },
        other => PoolError::Problem {
            status: other,
            code: problem
                .and_then(|problem| problem.code)
                .unwrap_or_else(|| "unknown".to_owned()),
            detail: if detail.is_empty() {
                String::new()
            } else {
                format!(": {detail}")
            },
        },
    }
}

#[cfg(test)]
pub(crate) mod testing {
    //! A pool that speaks the documented HTTP routes on a loopback socket.
    //!
    //! It is not a mock trait: the client under test uses [`HttpPool`], so the
    //! request line, the bearer header, the JSON bodies and the status handling
    //! are all exercised for real. The server never leaves the test process.

    use std::collections::BTreeMap;
    use std::io::{Read as _, Write as _};
    use std::net::TcpListener;
    use std::sync::atomic::{AtomicBool, Ordering};
    use std::sync::{Arc, Mutex};
    use std::thread::{self, JoinHandle};
    use std::time::{Duration, Instant};

    /// One request the server received.
    #[derive(Debug, Clone, PartialEq, Eq)]
    pub struct Captured {
        /// Method, as sent.
        pub method: String,
        /// Path, as sent.
        pub path: String,
        /// The `Authorization` header, when present.
        pub authorization: Option<String>,
        /// The request body.
        pub body: String,
    }

    impl Captured {
        /// The request body as JSON, when it parses.
        pub fn json(&self) -> serde_json::Value {
            serde_json::from_str(&self.body).unwrap_or(serde_json::Value::Null)
        }
    }

    type Route = (u16, String);

    /// The loopback pool. Dropping it stops the accept loop.
    pub struct ScriptedHttpPool {
        url: String,
        routes: BTreeMap<String, Route>,
        requests: Arc<Mutex<Vec<Captured>>>,
        stop: Arc<AtomicBool>,
        handle: Option<JoinHandle<()>>,
    }

    impl ScriptedHttpPool {
        /// Start a pool with `(method, path, status, body)` routes.
        pub fn start(routes: &[(&str, &str, u16, &str)]) -> Self {
            let listener = TcpListener::bind("127.0.0.1:0").expect("bind loopback");
            let address = listener.local_addr().expect("local address");
            listener
                .set_nonblocking(true)
                .expect("non-blocking listener");
            let url = format!("http://{address}");
            let table: BTreeMap<String, Route> = routes
                .iter()
                .map(|(method, path, status, body)| {
                    (format!("{method} {path}"), (*status, (*body).to_owned()))
                })
                .collect();
            let requests = Arc::new(Mutex::new(Vec::new()));
            let stop = Arc::new(AtomicBool::new(false));
            let thread_requests = Arc::clone(&requests);
            let thread_stop = Arc::clone(&stop);
            let thread_table = table.clone();
            let handle = thread::spawn(move || {
                while !thread_stop.load(Ordering::Relaxed) {
                    match listener.accept() {
                        Ok((mut stream, _)) => {
                            stream
                                .set_read_timeout(Some(Duration::from_secs(2)))
                                .expect("read timeout");
                            if let Some(captured) = read_request(&mut stream) {
                                let key = format!("{} {}", captured.method, captured.path);
                                let (status, body) =
                                    thread_table.get(&key).cloned().unwrap_or_else(|| {
                                        (404, "{\"code\":\"not_found\"}".to_owned())
                                    });
                                thread_requests.lock().expect("request log").push(captured);
                                let _ = respond(&mut stream, status, &body);
                            }
                        }
                        Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                            thread::sleep(Duration::from_millis(2));
                        }
                        Err(_) => break,
                    }
                }
            });
            Self {
                url,
                routes: table,
                requests,
                stop,
                handle: Some(handle),
            }
        }

        /// The base URL to give the client.
        pub fn url(&self) -> &str {
            &self.url
        }

        /// The routes this pool answers, for a clear test failure.
        pub fn routes(&self) -> impl Iterator<Item = &String> {
            self.routes.keys()
        }

        /// Stop the server and return every request it handled.
        pub fn finish(mut self) -> Vec<Captured> {
            self.stop.store(true, Ordering::Relaxed);
            if let Some(handle) = self.handle.take() {
                let _ = handle.join();
            }
            self.requests.lock().expect("request log").clone()
        }
    }

    impl Drop for ScriptedHttpPool {
        fn drop(&mut self) {
            self.stop.store(true, Ordering::Relaxed);
            if let Some(handle) = self.handle.take() {
                let _ = handle.join();
            }
        }
    }

    /// Read one HTTP/1.1 request with a `Content-Length` body.
    fn read_request(stream: &mut std::net::TcpStream) -> Option<Captured> {
        let deadline = Instant::now() + Duration::from_secs(2);
        let mut buffer = Vec::new();
        let mut chunk = [0_u8; 1024];
        loop {
            if let Some(head_end) = find(&buffer, b"\r\n\r\n") {
                let head = String::from_utf8_lossy(&buffer[..head_end]).into_owned();
                let content_length = head
                    .lines()
                    .find_map(|line| {
                        let (name, value) = line.split_once(':')?;
                        name.eq_ignore_ascii_case("content-length")
                            .then(|| value.trim().parse::<usize>().ok())
                            .flatten()
                    })
                    .unwrap_or(0);
                let body_start = head_end + 4;
                while buffer.len() < body_start + content_length {
                    let read = stream.read(&mut chunk).ok()?;
                    if read == 0 {
                        break;
                    }
                    buffer.extend_from_slice(&chunk[..read]);
                }
                let mut lines = head.lines();
                let request_line = lines.next()?;
                let mut parts = request_line.split_whitespace();
                let method = parts.next()?.to_owned();
                let path = parts.next()?.to_owned();
                let authorization = lines.find_map(|line| {
                    let (name, value) = line.split_once(':')?;
                    name.eq_ignore_ascii_case("authorization")
                        .then(|| value.trim().to_owned())
                });
                let body = String::from_utf8_lossy(
                    &buffer[body_start..(body_start + content_length).min(buffer.len())],
                )
                .into_owned();
                return Some(Captured {
                    method,
                    path,
                    authorization,
                    body,
                });
            }
            if Instant::now() > deadline {
                return None;
            }
            match stream.read(&mut chunk) {
                Ok(0) => return None,
                Ok(read) => buffer.extend_from_slice(&chunk[..read]),
                Err(_) => return None,
            }
        }
    }

    fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
        haystack
            .windows(needle.len())
            .position(|window| window == needle)
    }

    fn respond(stream: &mut std::net::TcpStream, status: u16, body: &str) -> std::io::Result<()> {
        let reason = match status {
            200 => "OK",
            201 => "Created",
            400 => "Bad Request",
            401 => "Unauthorized",
            403 => "Forbidden",
            404 => "Not Found",
            409 => "Conflict",
            410 => "Gone",
            _ => "Response",
        };
        let head = format!(
            "HTTP/1.1 {status} {reason}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n",
            body.len()
        );
        stream.write_all(head.as_bytes())?;
        stream.write_all(body.as_bytes())?;
        stream.flush()
    }
}

